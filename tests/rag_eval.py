def hit_rank(hits, answers):
    for r, h in enumerate(hits, 1):
        if any(h["law"] == law and h["article"].startswith(art + "(") for law, art in answers):
            return r
    return None


def main():
    print(f"질문 {len(CASES)}개, 청크 {len(index.load_index()[0])}개\n")
    res = {}
    for mode in ("keyword", "vector", "hybrid", "rerank"):
        ranks = [hit_rank(index.search(q, k=5, mode=mode), ans) for q, ans in CASES]
        res[mode] = ranks
        at = lambda k: sum(1 for r in ranks if r and r <= k) / len(ranks)
        print(f"{mode:8s} hit@1 {at(1):.0%}   hit@3 {at(3):.0%}   hit@5 {at(5):.0%}")
    rej = sum(1 for q in OFF_TOPIC if not index.search(q, k=5))
    print(f"\n무관한 질문 거절(빈 결과): {rej}/{len(OFF_TOPIC)}")
    print("\n[재순위 후에도 5위 안에 못 찾은 질문]")
    for (q, ans), r in zip(CASES, res["rerank"]):
        if not r or r > 5:
            print(f"  - {q}  (정답 {ans[0][0][:8]} {ans[0][1]} 등)")


if __name__ == "__main__":
    main()
